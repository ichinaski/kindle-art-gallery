#!/usr/bin/env python3
"""Write art/widths.lua: advance widths of the bar's fonts, so artd.lua can measure
text and shrink it to fit instead of cutting it. Rerun after changing the fonts.

  uv run --with fonttools python tools/fontwidths.py
"""
import os
from fontTools.ttLib import TTFont

ART = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "art")
FONTS = {"regular": "AtkinsonHyperlegible-Regular.ttf", "bold": "AtkinsonHyperlegible-Bold.ttf"}

out = ["-- generated by tools/fontwidths.py: advance width per codepoint, in 1/1000 em",
       "return {"]
for style, name in FONTS.items():
    f = TTFont(os.path.join(ART, "assets", "fonts", name))
    upm, hmtx = f["head"].unitsPerEm, f["hmtx"]
    widths = {cp: round(hmtx[g][0] * 1000 / upm) for cp, g in f.getBestCmap().items() if cp < 0x10000}
    out.append(f"  {style} = {{")
    items = [f"[{cp}]={w}" for cp, w in sorted(widths.items())]
    for i in range(0, len(items), 12):
        out.append("    " + ",".join(items[i:i + 12]) + ",")
    out.append("  },")
out.append("}")
with open(os.path.join(ART, "widths.lua"), "w") as fh:
    fh.write("\n".join(out) + "\n")
print("art/widths.lua written")
